const scoutRow = (key: string, sponsor: string, mode = "hosted") => s.db.add({ table: user, as: key, row: {
  name: c.text(`Agent ${key}`), email: c.null(), password: c.null(), role: c.text("agent"), kind: c.text("agent"), agent_mode: c.text(mode), brief: c.text("Keep the launch moving."), sponsor_id: ref(`${sponsor}.id`), status: c.text("active"), is_demo: c.bool(false),
} });
const lineOf = (who: string, as: string) => s.db.add({ table: agent.agent_connection, as, row: { user_id: ref(`${who}.id`), name: c.text("system:hosted"), kind: c.text("key"), scope: c.text("read_write"), revoked: c.bool(false), expires_at: withFilters(c.now(), fl.add(c.int(600000))) } });
const cmpBrief = (args: string, word: string) => expr(withFilters(ref(`${args}.brief`), fl.contains(c.text(word))), "=", c.bool(true));
const equal = (name: string, value: Value) => s.expect.to_equal({ expr: ref(name), value });
const is = (name: string, value: string) => equal(name, c.text(value));
const count = (name: string, n: number) => s.expect.to_equal({ expr: withFilters(ref(name), fl.count()), value: c.int(n) });
const says = (name: string, value: string) => s.expect.to_contain({ expr: ref(name), value: c.text(value) });

/** Ada is a member, Ben a guest in a space of his own, and Scout is a hosted agent in A, sponsored by Ada. B is a space Scout isn't in. */
