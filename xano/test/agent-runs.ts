const mention = (as: string, key: string, conversation = "chat", who = "ada", token = "ada_token") => s.api.call({ api: postMessageRoute, headers: bearer(token), as, input: { id: ref(`${conversation}.id`), client_msg_id: c.text(key), body: withFilters(c.text("<@"), fl.concat(ref("scout.id")), fl.concat(c.text("> what's left?"))) } });
const runs = (as: string) => s.db.query({ table: agent_run, sort: [{ sortBy: "id", dir: "asc" }], as });
const newest = (as: string) => s.db.query({ table: agent_run, sort: [{ sortBy: "id", dir: "desc" }], paging: { per_page: 1, metadata: false }, as: `${as}_rows` });
/** Binds `as` to the newest run, however it's changed. */
const reload = (as: string) => [newest(as), s.set_var(as, withFilters(ref(`${as}_rows`), fl.first()))];
const reloadOne = (id: Value, as: string) => s.db.get({ table: agent_run, fieldValue: id, as });

/** A queued run on a new mention, ready for the stub: claimed by the runner, on Scout's line, and going. */
const working = (as: string, key = "ask") => [
  mention("asked", key),
  ...reload(as),
  s.db.patch({ table: agent_run, fieldValue: ref(`${as}.id`), data: obj({ status: c.text("claimed"), connection_id: ref("line.id") }) }),
  s.function.call({ fn: beginRun, as: "thread", input: { run_id: ref(`${as}.id`) } }),
];

/** The tool results a model's envelope would hold, as a step each. */
const step = (toolName: string, output: Value) => withFilters(c.array([]), fl.array_push(obj({ type: c.text("tool-result"), toolName: c.text(toolName), output })));
const envelope = (...steps: Value[]) => withFilters(c.array([]), ...steps.map((content) => fl.array_push(obj({ content }))));
const ok = obj({ ok: c.bool(true) });
const finish = (id: Value, steps: Value, error = "") => s.function.call({ fn: finishRun, as: "finished", input: { run_id: id, attempt: c.int(1), error: c.text(error), steps } });
const report = (id: Value, state: string, note = "Working on it.") => s.function.call({ fn: reportProgress, as: "reported", input: { actor_id: ref("scout.id"), run_id: id, note: c.text(note), state: c.text(state) } });
const gate = (id: Value, connection: Value = ref("line.id"), actor = "scout") => s.function.call({ fn: memberGate, as: "gated", input: { actor_id: ref(`${actor}.id`), connection_id: connection, run_id: id, attempt: c.int(1) } });
/** Finds the rows a refusal needs, because `to_throw` runs in a stack of its own. */
const lookUp = [
  s.db.query({ table: user, where: cmp(col("name"), "=", c.text("Agent scout")), returnType: "single", as: "scout" }),
  s.db.query({ table: agent_run, sort: [{ sortBy: "id", dir: "desc" }], paging: { per_page: 1, metadata: false }, as: "latest" }),
  s.set_var("run", withFilters(ref("latest"), fl.first())),
];
/** The newest run's next tool call, turned away with these words. */
const gateRefuses = (words: string) => s.expect.to_throw({ exception: c.text(words), body: [
  ...lookUp,
  s.function.call({ fn: memberGate, as: "gated", input: { actor_id: ref("scout.id"), connection_id: ref("run.connection_id"), run_id: ref("run.id"), attempt: ref("run.attempt") } }),
] });

/** Another hosted agent in space A, on its own line. */
const teammate = (key: string) => [scoutRow(key, "ada"), lineOf(key, `${key}_line`), joined("a", key)];
/** The newest run, claimed by the runner on this agent's line and going. */
const going = (as: string, agent: string) => [
  ...reload(as),
  equal(`${as}.agent_id`, ref(`${agent}.id`)),
  s.db.patch({ table: agent_run, fieldValue: ref(`${as}.id`), data: obj({ status: c.text("claimed"), connection_id: ref(`${agent}_line.id`) }) }),
  s.function.call({ fn: beginRun, as: `${as}_thread`, input: { run_id: ref(`${as}.id`) } }),
];
/** A run's agent says something in its own thread, naming another agent. */
const names = (from: string, run: string, to: string) => s.function.call({ fn: speak, as: `${from}_said`, input: { actor_id: ref(`${from}.id`), run_id: ref(`${run}.id`), conversation_id: c.int(0), body: withFilters(c.text("<@"), fl.concat(ref(`${to}.id`)), fl.concat(c.text("> can you take this on?"))) } });
/** A row that used up part of a day's or an hour's limit. */
const pastRun = (agent: string, i: number, extra: Record<string, Value>) => s.db.add({ table: agent_run, as: `past_${i}`, row: { agent_id: ref(`${agent}.id`), requested_by: ref("ada.id"), source_type: c.text("task"), source_id: c.int(9000 + i), status: c.text("done"), attempt: c.int(1), is_demo: c.bool(false), ...extra } });
const spentToday = (agent: string, n: number) => Array.from({ length: n }, (_, i) => pastRun(agent, i, { spent_at: c.now() }));
const tokenFor = (id: Value, as: string, extras: Value = c.obj({})) => s.security.create_auth_token({ table: agent.agent_connection, id, extras, expiration: c.int(300), as });
const keyOf = (who: string, as: string) => s.db.add({ table: agent.agent_connection, as, row: { user_id: ref(`${who}.id`), name: c.text("Laptop key"), kind: c.text("key"), scope: c.text("read_write"), revoked: c.bool(false), expires_at: withFilters(c.now(), fl.add(c.int(600000))) } });
const door = (token: string) => s.api.call({ api: executeRun, headers: bearer(token), as: "opened" });
const named = (key: string, as = key) => s.db.query({ table: user, where: cmp(col("name"), "=", c.text(`Agent ${key}`)), returnType: "single", as });
const member = (key: string) => s.db.query({ table: user, where: cmp(col("name"), "=", c.text(`Test ${key}`)), returnType: "single", as: key });

/**
 * The stub in the model's seat for a brief: the one thing a run's agent is told about how to work. It reads the args the door hands
 * a model, and does what that brief says, so two agents differ only by what `runArgs` gives them.
 */
const stubModel = (run: string, agent: string) => [
  s.function.call({ fn: runArgs, as: `${run}_args`, input: { run_id: ref(`${run}.id`) } }),
  s.conditional({
    when: cmpBrief(`${run}_args`, "tasks"),
    then: [s.function.call({ fn: saveTask, as: `${run}_saved`, input: { actor_id: ref(`${agent}.id`), run_id: ref(`${run}.id`), project_id: ref("launch.id"), title: c.text("Book the checkout test"), description: c.text(""), status: c.text(""), priority: c.text(""), due_on: c.text(""), id: c.int(0), assignee_id: c.int(0) } })],
    else: [s.function.call({ fn: speak, as: `${run}_said`, input: { actor_id: ref(`${agent}.id`), run_id: ref(`${run}.id`), conversation_id: c.int(0), body: c.text("Two things are left.") } })],
  }),
  s.function.call({ fn: reportProgress, as: `${run}_done`, input: { actor_id: ref(`${agent}.id`), run_id: ref(`${run}.id`), note: c.text("Finished."), state: c.text("done") } }),
  finish(ref(`${run}.id`), envelope(step("report_progress", ok))),
];

